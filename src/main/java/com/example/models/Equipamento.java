package com.example.models;

public class Equipamento {

    private String nomeItem;
    private String descricaoItem;
    private String atributoItem;

    // getters e setters
    public String getNomeItem() {
        return nomeItem;
    }

    public void setNomeItem(String nomeItem) {
        this.nomeItem = nomeItem;
    }

    public String getDescricaoItem() {
        return descricaoItem;
    }

    public void setDescricaoItem(String descicaoItem) {
        this.descricaoItem = descicaoItem;
    }

    public String getAtributoItem() {
        return atributoItem;
    }

    public void setAtributoItem(String atributoItem) {
        this.atributoItem = atributoItem;
    }
    
}
